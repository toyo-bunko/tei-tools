/* ======== TEI Gallery ========
   A two-pane launcher: pick an XML document (left) and an XSL stylesheet
   (right), then open that combination full-screen in view.html.

   Both XML and XSL listings come from catalog.json, generated by
   scripts/build-catalog.mjs (XML from each teiHeader; XSL from each
   stylesheet's leading comment: Id, Input, Sample, Title, Description,
   Category, License). No hand-maintained list in JS.

   Page state lives in the query string so a filtered / selected pair can
   be shared via URL:
     ?xml-q=<q>             text filter for the XML pane
     ?xml-cat=A,B           XML categories (OR-joined within facet)
     ?xml-lang=en,ja        XML languages (OR-joined)
     ?xsl-q=<q>             text filter for the XSL pane
     ?xsl-cat=A,B           XSL categories
     ?xml=<id>              selected XML id
     ?xsl=<id>              selected XSL id
   Facets are AND-joined across kinds (e.g. cat:A AND lang:en). */

/* ---- State ---- */
let catalog       = { xml: [], xsl: [] };  // loaded from catalog.json
let addedXmls     = [];     // user-added entries (scope: 'added')
let selectedXml   = null;
let selectedXsl   = null;
let xmlFilter     = '';
let xslFilter     = '';
let xmlCatFilter  = new Set();
let xmlLangFilter = new Set();
let xslCatFilter  = new Set();
let addCounter    = 0;

/* ---- Elements ---- */
const xmlListEl        = document.getElementById('xmlList');
const xslListEl        = document.getElementById('xslList');
const xmlCountEl       = document.getElementById('xmlCount');
const xmlFilterEl      = document.getElementById('xmlFilter');
const xslFilterEl      = document.getElementById('xslFilter');
const xmlFilterCountEl = document.getElementById('xmlFilterCount');
const xslFilterCountEl = document.getElementById('xslFilterCount');
const xmlFacetsEl      = document.getElementById('xmlFacets');
const xslFacetsEl      = document.getElementById('xslFacets');
const selXmlEl         = document.getElementById('selXml');
const selXslEl         = document.getElementById('selXsl');
const openBtn          = document.getElementById('pubOpenBtn');
const shareBtn         = document.getElementById('pubShareBtn');
const urlInput         = document.getElementById('xmlUrlInput');
const urlBtn           = document.getElementById('xmlUrlBtn');
const fileBtn          = document.getElementById('xmlFileBtn');
