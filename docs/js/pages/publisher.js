/* The view link's inner markup: icon + label (e.g. "XML を見る"). */
function viewContent(labelKey) { return OPEN_ICON + '<span>' + esc(t(labelKey)) + '</span>'; }

/* Build the chip row shown under the description: category + languages.
   `opts.skipCategory` omits the category chip — used in the XSL list,
   where the section heading already names the category. */
function metaRow(entry, opts) {
  opts = opts || {};
  const chips = [];
  if (entry.category && !opts.skipCategory) {
    chips.push('<span class="pub-cat">' + esc(entry.category) + '</span>');
  }
  (entry.languages || []).forEach(code => {
    chips.push('<span class="pub-lang">' + esc(String(code).toUpperCase()) + '</span>');
  });
  return chips.length ? '<div class="pub-item-meta">' + chips.join('') + '</div>' : '';
}

/* License line (TEI publicationStmt/availability). */
function licenseRow(entry) {
  return entry.license
    ? '<p class="pub-license"><span class="pub-license-label">' +
        esc(t('pubLicense')) + '</span> ' + esc(entry.license) + '</p>'
    : '';
}

/* "View" link — opens the .xml / .xsl in a new browser tab.
   Sits at the right end of the card head (no download attribute,
   so the browser shows the file directly). */
function viewLink(url, labelKey) {
  return '<a class="pub-open" href="' + esc(url) + '" ' +
    'target="_blank" rel="noopener" title="' + esc(t(labelKey)) + '">' +
    viewContent(labelKey) + '</a>';
}

/* ---- Filtering ----
   Text needle is OR-joined across (title, description, category, id, url).
   Facet sets are AND-joined across kinds; within a kind any one value
   matches. An empty Set means "no constraint on this facet". */
function textMatches(entry, q) {
  if (!q) return true;
  const needle = q.toLowerCase();
  const hay = [entry.title, entry.description, entry.category,
               entry.id, entry.url]
    .filter(Boolean).join(' ').toLowerCase();
  return hay.indexOf(needle) !== -1;
}
function categoryMatches(entry, set) {
  return !set || !set.size || set.has(entry.category || '—');
}
function languagesMatch(entry, set) {
  if (!set || !set.size) return true;
  const langs = entry.languages || [];
  return langs.some(l => set.has(l));
}
function xmlMatches(entry) {
  return textMatches(entry, xmlFilter)
      && categoryMatches(entry, xmlCatFilter)
      && languagesMatch(entry, xmlLangFilter);
}
function xslMatches(entry) {
  return textMatches(entry, xslFilter)
      && categoryMatches(entry, xslCatFilter);
}

/* Collect unique facet values with their (unfiltered) occurrence counts.
   `accessor` returns an array of values for one entry. */
function tallyFacet(entries, accessor) {
  const counts = new Map();
  entries.forEach(e => {
    accessor(e).forEach(v => {
      if (!v) return;
      counts.set(v, (counts.get(v) || 0) + 1);
    });
  });
  return [...counts.entries()].sort((a, b) =>
    a[0].localeCompare(b[0], undefined, { numeric: true }));
}

/* Render a facet block: "Label: [chip] [chip] [×]".
   `items` is an array of [value, count]. `display` formats the chip
   label (defaults to the raw value). `onChange` runs after each
   toggle / clear and is expected to re-render. */
function renderFacetBlock(container, labelText, items, activeSet, onChange, display) {
  if (!items.length) return;
  const labelEl = document.createElement('span');
  labelEl.className = 'pub-facet-label';
  labelEl.textContent = labelText;
  container.appendChild(labelEl);
  items.forEach(([val, n]) => {
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'pub-chip' + (activeSet.has(val) ? ' active' : '');
    btn.innerHTML = esc((display ? display(val) : val)) +
      ' <span class="pub-chip-n">' + n + '</span>';
    btn.addEventListener('click', () => {
      if (activeSet.has(val)) activeSet.delete(val);
      else activeSet.add(val);
      onChange();
    });
    container.appendChild(btn);
  });
  if (activeSet.size) {
    const clear = document.createElement('button');
    clear.type = 'button';
    clear.className = 'pub-facet-clear';
    clear.textContent = '×';
    clear.title = 'clear';
    clear.addEventListener('click', () => { activeSet.clear(); onChange(); });
    container.appendChild(clear);
  }
}

function rerenderXml() {
  renderXmlFacets(); renderXmlList(); refresh(); syncUrl();
}
function rerenderXsl() {
  renderXslFacets(); renderXslList(); refresh(); syncUrl();
}

function renderXmlFacets() {
  if (!xmlFacetsEl) return;
  xmlFacetsEl.innerHTML = '';
  const xmls = allXmls();
  const cats  = tallyFacet(xmls, e => [e.category]);
  const langs = tallyFacet(xmls, e => e.languages || []);
  renderFacetBlock(xmlFacetsEl, t('pubFacetCategory') || 'Category',
    cats, xmlCatFilter, rerenderXml);
  renderFacetBlock(xmlFacetsEl, t('pubFacetLanguage') || 'Lang',
    langs, xmlLangFilter, rerenderXml,
    v => String(v).toUpperCase());
}

function renderXslFacets() {
  if (!xslFacetsEl) return;
  xslFacetsEl.innerHTML = '';
  const xsls = catalog.xsl || [];
  const cats = tallyFacet(xsls, e => [e.category]);
  renderFacetBlock(xslFacetsEl, t('pubFacetCategory') || 'Category',
    cats, xslCatFilter, rerenderXsl);
}

function updateFilterCount(el, visible, total, active) {
  if (!el) return;
  if (!active) { el.textContent = ''; return; }
  const tpl = t('pubFilterCount') || '{visible} / {total}';
  el.textContent = tpl.replace('{visible}', visible).replace('{total}', total);
}

function emptyHit() {
  const li = document.createElement('li');
  li.className = 'pub-empty';
  li.textContent = t('pubFilterNoHit') || '—';
  return li;
}

/* ======== Rendering ======== */
function allXmls() { return catalog.xml.concat(addedXmls); }

function hasActiveFilter(kind) {
  if (kind === 'xml') return !!xmlFilter || xmlCatFilter.size || xmlLangFilter.size;
  if (kind === 'xsl') return !!xslFilter || xslCatFilter.size;
  return false;
}

function renderXmlList() {
  const xmls = allXmls();
  xmlCountEl.textContent = '(' + xmls.length + ')';
  xmlListEl.innerHTML = '';
  const visible = xmls.filter(xmlMatches);
  updateFilterCount(xmlFilterCountEl, visible.length, xmls.length,
    hasActiveFilter('xml'));
  if (!visible.length) { xmlListEl.appendChild(emptyHit()); return; }
  visible.forEach(entry => xmlListEl.appendChild(renderXmlItem(entry)));
}

function renderXmlItem(entry) {
  const li = document.createElement('li');
  li.className = 'pub-item' +
    (selectedXml && selectedXml.id === entry.id ? ' selected' : '');
  li.dataset.id = entry.id;
  li.innerHTML =
    '<div class="pub-item-head">' +
      '<span class="pub-item-title">' +
        '<span class="pub-item-title-text">' + esc(entry.title || entry.url) + '</span>' +
      '</span>' +
      viewLink(entry.url, 'pubViewXml') +
    '</div>' +
    (entry.description
      ? '<p class="pub-item-note">' + esc(entry.description) + '</p>' : '') +
    metaRow(entry) +
    licenseRow(entry);
  li.addEventListener('click', e => {
    if (e.target.closest('.pub-open')) return;
    selectedXml = entry; refresh(); syncUrl();
  });
  return li;
}

/* Group XSL entries by `category`, putting the generic group first. */
function groupXslByCategory(entries) {
  const groups = new Map();
  entries.forEach(entry => {
    const cat = entry.category || '—';
    if (!groups.has(cat)) groups.set(cat, []);
    groups.get(cat).push(entry);
  });
  const cats = [...groups.keys()].sort((a, b) => {
    const ag = /汎用|General/i.test(a) ? 0 : 1;
    const bg = /汎用|General/i.test(b) ? 0 : 1;
    return ag - bg;   // ties keep insertion order via stable sort
  });
  return cats.map(cat => ({ cat, items: groups.get(cat) }));
}

function renderXslList() {
  xslListEl.innerHTML = '';
  const xsls = catalog.xsl || [];
  const visible = xsls.filter(xslMatches);
  updateFilterCount(xslFilterCountEl, visible.length, xsls.length,
    hasActiveFilter('xsl'));
  if (!visible.length) { xslListEl.appendChild(emptyHit()); return; }
  const grouped = groupXslByCategory(visible);
  grouped.forEach(group => {
    const head = document.createElement('li');
    head.className = 'pub-section-head';
    head.textContent = group.cat;
    xslListEl.appendChild(head);
    group.items.forEach(entry => xslListEl.appendChild(renderXslItem(entry)));
  });
}

function renderXslItem(entry) {
  const li = document.createElement('li');
  li.className = 'pub-item' +
    (selectedXsl && selectedXsl.id === entry.id ? ' selected' : '');
  li.dataset.id = entry.id;
  li.innerHTML =
    '<div class="pub-item-head">' +
      '<span class="pub-item-title">' +
        '<span class="pub-item-title-text">' + esc(entry.title || entry.id || entry.url) + '</span>' +
      '</span>' +
      viewLink(entry.url, 'pubViewXsl') +
    '</div>' +
    (entry.description
      ? '<p class="pub-item-note">' + esc(entry.description) + '</p>' : '') +
    metaRow(entry, { skipCategory: true }) +
    licenseRow(entry);
  li.addEventListener('click', e => {
    if (e.target.closest('.pub-open')) return;
    selectedXsl = entry; refresh(); syncUrl();
  });
  return li;
}

/* Reflect a step's state on its pane / bar: 'done' (selected),
   'active' (do this now), '' (pending). Highlights the block the
   user should act on next. */
function setStep(name, state) {
  const el = document.querySelector('[data-step="' + name + '"]');
  if (!el) return;
  el.classList.toggle('done',   state === 'done');
  el.classList.toggle('active', state === 'active');
}

/* Update selection highlight, the step guide, the selection bar, and the button. */
function refresh() {
  document.querySelectorAll('#xmlList .pub-item').forEach(li =>
    li.classList.toggle('selected', !!selectedXml && li.dataset.id === selectedXml.id));
  document.querySelectorAll('#xslList .pub-item').forEach(li =>
    li.classList.toggle('selected', !!selectedXsl && li.dataset.id === selectedXsl.id));

  selXmlEl.textContent = selectedXml ? (selectedXml.title || selectedXml.url) : t('pubNone');
  selXmlEl.classList.toggle('pub-none', !selectedXml);
  selXslEl.textContent = selectedXsl ? (selectedXsl.title || selectedXsl.id || selectedXsl.url) : t('pubNone');
  selXslEl.classList.toggle('pub-none', !selectedXsl);

  const ready = !!(selectedXml && selectedXsl);
  setStep('xml',  selectedXml ? 'done' : 'active');
  setStep('xsl',  selectedXsl ? 'done' : (selectedXml ? 'active' : ''));
  setStep('open', ready ? 'active' : '');

  openBtn.disabled = !ready;
}

/* ======== URL <-> state sync ======== */
function setCsv(set) { return [...set].join(','); }
function csvSet(str) {
  return new Set((str || '').split(',').map(s => s.trim()).filter(Boolean));
}

function syncUrl() {
  const params = new URLSearchParams();
  if (xmlFilter)         params.set('xml-q', xmlFilter);
  if (xmlCatFilter.size) params.set('xml-cat', setCsv(xmlCatFilter));
  if (xmlLangFilter.size)params.set('xml-lang', setCsv(xmlLangFilter));
  if (xslFilter)         params.set('xsl-q', xslFilter);
  if (xslCatFilter.size) params.set('xsl-cat', setCsv(xslCatFilter));
  if (selectedXml)       params.set('xml', selectedXml.id);
  if (selectedXsl)       params.set('xsl', selectedXsl.id);
  const qs = params.toString();
  const newUrl = location.pathname + (qs ? '?' + qs : '') + location.hash;
  history.replaceState(null, '', newUrl);
}

function readUrlIntoState() {
  const params = new URLSearchParams(location.search);
  xmlFilter     = params.get('xml-q') || '';
  xslFilter     = params.get('xsl-q') || '';
  xmlCatFilter  = csvSet(params.get('xml-cat'));
  xmlLangFilter = csvSet(params.get('xml-lang'));
  xslCatFilter  = csvSet(params.get('xsl-cat'));
  if (xmlFilterEl) xmlFilterEl.value = xmlFilter;
  if (xslFilterEl) xslFilterEl.value = xslFilter;
  const xmlId = params.get('xml');
  const xslId = params.get('xsl');
  if (xmlId) {
    const e = allXmls().find(x => x.id === xmlId);
    if (e) selectedXml = e;
  }
  if (xslId) {
    const e = (catalog.xsl || []).find(x => x.id === xslId);
    if (e) selectedXsl = e;
  }
}

/* ======== Open full-screen (in a new tab) ========
   Pass the XSL by URL (not by id) so view.js does not need its own
   id-resolution table — the catalog's `url` is the single source of truth. */
openBtn.addEventListener('click', () => {
  if (!selectedXml || !selectedXsl) return;
  const url = 'view.html?url=' + encodeURIComponent(selectedXml.url) +
    '&xsl=' + encodeURIComponent(selectedXsl.url);
  window.open(url, '_blank', 'noopener');
});

/* ======== Share link ======== */
if (shareBtn) {
  shareBtn.addEventListener('click', async () => {
    const text = location.href;
    try {
      if (navigator.clipboard && navigator.clipboard.writeText) {
        await navigator.clipboard.writeText(text);
      } else {
        const ta = document.createElement('textarea');
        ta.value = text; document.body.appendChild(ta);
        ta.select(); document.execCommand('copy');
        document.body.removeChild(ta);
      }
      const orig = shareBtn.textContent;
      shareBtn.textContent = t('pubShared') || '✓';
      shareBtn.classList.add('pub-share-ok');
      setTimeout(() => {
        shareBtn.textContent = orig;
        shareBtn.classList.remove('pub-share-ok');
      }, 1500);
    } catch (e) { /* clipboard blocked — silent */ }
  });
}

/* ======== Filter input wiring ======== */
if (xmlFilterEl) {
  xmlFilterEl.addEventListener('input', () => {
    xmlFilter = xmlFilterEl.value;
    renderXmlList(); refresh(); syncUrl();
  });
}
if (xslFilterEl) {
  xslFilterEl.addEventListener('input', () => {
    xslFilter = xslFilterEl.value;
    renderXslList(); refresh(); syncUrl();
  });
}

/* ======== Add an XML ======== */
function addXmlEntry(url, title) {
  const entry = {
    id: 'added-' + (++addCounter), scope: 'added', url: url,
    title: title, description: '', languages: [], category: '', license: '',
  };
  addedXmls.push(entry);
  selectedXml = entry;
  renderXmlList();
  refresh();
  syncUrl();
}

urlBtn.addEventListener('click', () => {
  hideError();
  const url = urlInput.value.trim();
  if (!url) { showError(t('errXmlUrl')); return; }
  addXmlEntry(url, url.split('/').pop() || url);
  urlInput.value = '';
});
urlInput.addEventListener('keydown', e => { if (e.key === 'Enter') urlBtn.click(); });

fileBtn.addEventListener('click', () => fileInput.click());
fileInput.addEventListener('change', () => {
  const file = fileInput.files && fileInput.files[0];
  if (file) {
    // A blob: URL works across same-origin pages within this session,
    // so view.html can fetch it. (Relative <graphic url> images won't
    // resolve for an uploaded single file — fine for non-image XSLs.)
    addXmlEntry(URL.createObjectURL(file), file.name);
  }
  fileInput.value = '';
});

/* ======== Init ======== */
function renderAll() {
  renderXmlFacets(); renderXmlList();
  renderXslFacets(); renderXslList();
  refresh();
}

fetch('catalog.json')
  .then(res => { if (!res.ok) throw new Error('HTTP ' + res.status); return res.json(); })
  .then(data => {
    catalog = data;
    readUrlIntoState();      // resolve ?xml / ?xsl ids now that catalog is loaded
    renderAll();
    syncUrl();               // canonicalise the URL (drop unknown ids)
  })
  .catch(() => { showError(t('errCatalog')); renderAll(); });

// Re-render localized labels (badges/links) after the language toggle.
document.getElementById('langBtn').addEventListener('click', renderAll);
